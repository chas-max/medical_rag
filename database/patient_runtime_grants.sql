-- Owner-run psql only, after migrations 0001-0007 and external role audit:
-- psql ... -v runtime_role=patient_runtime -f database/patient_runtime_grants.sql
-- runtime_role must already be a dedicated NOSUPERUSER NOBYPASSRLS,
-- NOCREATEDB NOCREATEROLE NOREPLICATION role, with no privileged memberships,
-- schema CREATE, table ownership, DDL or inherited broader/PUBLIC authority.
-- This grant recipe does NOT revoke/audit old/inherited/PUBLIC permissions,
-- create roles/accounts, provision verification, or auto-apply migrations.
\set ON_ERROR_STOP on
BEGIN;
GRANT USAGE ON SCHEMA medical_rag TO :"runtime_role";
GRANT EXECUTE ON FUNCTION medical_rag.runtime_role_basic_check() TO :"runtime_role";
GRANT SELECT (tenant_id, active, session_version) ON medical_rag.tenants TO :"runtime_role";
GRANT SELECT (tenant_id, account_id, issuer, subject, active, session_version)
    ON medical_rag.identity_accounts TO :"runtime_role";
GRANT SELECT (tenant_id, account_id, role) ON medical_rag.identity_roles TO :"runtime_role";
GRANT SELECT (tenant_id, account_id, patient_id, verified) ON medical_rag.identity_bindings TO :"runtime_role";
GRANT SELECT (tenant_id, patient_id, age_classification, identity_verified)
    ON medical_rag.patient_subjects TO :"runtime_role";
-- Harmless key UPDATE is solely required by PostgreSQL SELECT FOR UPDATE.
GRANT UPDATE (patient_id) ON medical_rag.patient_subjects TO :"runtime_role";
GRANT SELECT (token_hash, csrf_hash, tenant_id, account_id, mfa_verified,
    account_version, tenant_version, created_at, last_seen_at, expires_at, revoked, authenticated_at, provider_sid_hash),
    INSERT (token_hash, csrf_hash, tenant_id, account_id, mfa_verified,
    account_version, tenant_version, expires_at, authenticated_at, provider_sid_hash), UPDATE (last_seen_at, revoked)
    ON medical_rag.identity_sessions TO :"runtime_role";
GRANT SELECT (tenant_id, state_hash, browser_hash, tenant_version, encrypted_context, created_at, expires_at),
    INSERT (tenant_id, state_hash, browser_hash, tenant_version, encrypted_context, expires_at), DELETE
    ON medical_rag.oidc_login_transactions TO :"runtime_role";
-- PostgreSQL FOR UPDATE on login rows needs UPDATE on a harmless key.
GRANT UPDATE (state_hash) ON medical_rag.oidc_login_transactions TO :"runtime_role";
GRANT SELECT (tenant_id, patient_id, conversation_id, title, created_at),
    INSERT (tenant_id, patient_id, conversation_id, title)
    ON medical_rag.conversations TO :"runtime_role";
GRANT SELECT (tenant_id, patient_id, conversation_id, turn_id, content, created_at),
    INSERT (tenant_id, patient_id, conversation_id, turn_id, content)
    ON medical_rag.conversation_turns TO :"runtime_role";
GRANT SELECT (event_id, tenant_id, patient_id, grantor_account_id, purpose,
    notice_version, granted, recorded_at, expires_at, event_order),
    INSERT (event_id, tenant_id, patient_id, grantor_account_id, purpose,
    notice_version, granted, expires_at)
    ON medical_rag.patient_consent_events TO :"runtime_role";
GRANT SELECT (event_id, tenant_id, operator_id, action, resource_type, outcome,
    reason_code, recorded_at, event_order, request_id),
    INSERT (tenant_id, operator_id, action, resource_type, outcome, reason_code, request_id)
    ON medical_rag.security_audit_events TO :"runtime_role";
GRANT SELECT (event_id, tenant_id, issuer, jti_hash, subject_hash, sid_hash, issued_at, expires_at, recorded_at),
    INSERT (tenant_id, issuer, jti_hash, subject_hash, sid_hash, issued_at, expires_at)
    ON medical_rag.provider_logout_events TO :"runtime_role";
-- No UPDATE/DELETE/TRUNCATE, DDL, ownership or BYPASSRLS. Server event UUID,
-- time and identity order are not insertable columns. Identity sequence is
-- generated by PostgreSQL and needs no extra runtime sequence privilege.
GRANT SELECT (tenant_id,case_id,requester_account_id,category,status,assigned_account_id,resolution_code,created_at,updated_at),
    INSERT (tenant_id,case_id,requester_account_id,category), UPDATE (status,assigned_account_id,resolution_code)
    ON medical_rag.support_cases TO :"runtime_role";
COMMIT;
